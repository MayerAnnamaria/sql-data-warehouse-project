/* ============================================================================
   SQL DATA WAREHOUSE | PART-TO-WHOLE ANALYSIS
   ============================================================================
   Project       : Data Warehouse Analytics
   Database      : DataWarehouseAnalytics
   SQL dialect   : Microsoft SQL Server (T-SQL)
   Source tables : gold.fact_sales, gold.dim_products
   File          : 11_part_to_whole_analysis.sql

   PURPOSE
   Analyze how individual product categories contribute to total business
   sales revenue. Part-to-whole analysis expresses a category's share as a
   percentage of the total across all categories.

   BUSINESS QUESTIONS
   01. How much revenue does each product category generate?
   02. What proportion of overall revenue does each category contribute?
   03. Do category revenue contributions reconcile to total sales revenue?

   TECHNIQUES
   LEFT JOIN | COALESCE | GROUP BY | CTE | SUM() OVER () | NULLIF | ROUND

   ASSUMPTIONS
   - Each fact row represents one sales line; sales_amount is its revenue.
   - gold.dim_products contains one row per product_key. If product_key is not
     unique in the dimension, joining it may inflate sales totals.
   - A missing product match or NULL category is labeled 'Uncategorized'.
   - Revenue share is calculated on all sales, including unmatched products.
   - Shares are numeric percentages, not formatted strings, so downstream
     dashboards and calculations can use them directly.

   EXECUTION
   Run in SQL Server Management Studio or VS Code with a SQL Server connection.
   All statements are read-only. Review business definitions before reuse.
   ============================================================================ */

USE DataWarehouseAnalytics;
GO

/* ============================================================================
   01 | REVENUE CONTRIBUTION BY PRODUCT CATEGORY

   Business question:
   How much of total sales revenue is generated by each product category?

   Output grain: One row per product category, including 'Uncategorized'.
   ============================================================================ */

-- 01.01 | Aggregate sales revenue at the product-category level.
SELECT
    COALESCE(p.category, 'Uncategorized') AS category,
    SUM(f.sales_amount) AS category_revenue
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON p.product_key = f.product_key
GROUP BY
    COALESCE(p.category, 'Uncategorized')
ORDER BY
    category_revenue DESC,
    category;


/* ============================================================================
   02 | PART-TO-WHOLE REVENUE SHARE

   Business question:
   What percentage of overall sales revenue comes from each category?

   Formula:
   Revenue share (%) = (Category revenue / Overall revenue) * 100

   Notes:
   - SUM(category_revenue) OVER () calculates the overall revenue without
     collapsing the category-level rows.
   - 100.0 ensures non-integer division.
   - NULLIF prevents division by zero when overall revenue equals zero.
   - Percentages are rounded to two decimal places and may not sum to exactly
     100.00 because of rounding.
   ============================================================================ */

-- 02.01 | Calculate category revenue, overall revenue, and revenue share.
WITH category_sales AS (
    SELECT
        COALESCE(p.category, 'Uncategorized') AS category,
        SUM(f.sales_amount) AS category_revenue
    FROM gold.fact_sales AS f
    LEFT JOIN gold.dim_products AS p
        ON p.product_key = f.product_key
    GROUP BY
        COALESCE(p.category, 'Uncategorized')
)
SELECT
    category,
    category_revenue,
    SUM(category_revenue) OVER () AS overall_revenue,
    ROUND(
        100.0 * category_revenue
        / NULLIF(SUM(category_revenue) OVER (), 0),
        2
    ) AS revenue_share_pct
FROM category_sales
ORDER BY
    category_revenue DESC,
    category;


/* ============================================================================
   03 | RECONCILIATION CHECK

   Business question:
   Does the total revenue attributed to product categories equal the revenue
   recorded in the fact table?

   Expected result:
   revenue_difference = 0, provided each product_key appears at most once
   in gold.dim_products. A nonzero difference suggests duplicated product
   keys or another join-related issue requiring investigation.
   ============================================================================ */

-- 03.01 | Compare fact-table revenue with aggregated category revenue.
WITH category_sales AS (
    SELECT
        COALESCE(p.category, 'Uncategorized') AS category,
        SUM(f.sales_amount) AS category_revenue
    FROM gold.fact_sales AS f
    LEFT JOIN gold.dim_products AS p
        ON p.product_key = f.product_key
    GROUP BY
        COALESCE(p.category, 'Uncategorized')
),
revenue_totals AS (
    SELECT
        (SELECT SUM(sales_amount) FROM gold.fact_sales) AS fact_revenue,
        (SELECT SUM(category_revenue) FROM category_sales) AS allocated_revenue
)
SELECT
    fact_revenue,
    allocated_revenue,
    COALESCE(allocated_revenue, 0) - COALESCE(fact_revenue, 0)
        AS revenue_difference
FROM revenue_totals;


